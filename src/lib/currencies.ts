function getCurrencyName(code: string): string {
  try {
    return new Intl.DisplayNames(["en"], { type: "currency" }).of(code) ?? code;
  } catch {
    return code;
  }
}

export const CURRENCIES: readonly CurrencyOption[] = CURRENCY_CODES.map((code) => ({
  value: code,
  label: `${getCurrencyName(code)} (${code})`,
}));
