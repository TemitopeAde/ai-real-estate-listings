export function isWidgetLangCode(value: unknown): value is WidgetLangCode {
  return typeof value === "string" && (WIDGET_LANG_CODES as readonly string[]).includes(value);
}

export function normalizeWidgetLanguage(value: unknown): WidgetLanguageSetting {
  if (value === "auto" || isWidgetLangCode(value)) return value;
  return "auto";
}

export function mapToSupportedLanguage(code: string): WidgetLangCode {
  const normalized = code.trim().toLowerCase().replace("_", "-");
  const base = normalized.split("-")[0] ?? "en";
  if (base === "zh") return "zh";
  if (isWidgetLangCode(base)) return base;
  return "en";
}

export function widgetTextDirection(lang: WidgetLangCode): "ltr" | "rtl" {
  return lang === "ar" ? "rtl" : "ltr";
}

async function readString(loader: () => unknown): Promise<string> {
  try {
    const value = loader();
    const resolved = typeof value === "object" && value !== null && "then" in value
      ? await (value as Promise<unknown>)
      : value;
    return typeof resolved === "string" ? resolved.trim() : "";
  } catch {
    return "";
  }
}

export async function resolveWidgetLanguage(setting: WidgetLanguageSetting): Promise<WidgetLangCode> {
  if (isWidgetLangCode(setting)) return setting;
  const fromEssentials = await readString(() => i18n.getLanguage());
  if (fromEssentials) return mapToSupportedLanguage(fromEssentials);
  const fromWindow = await readString(() => multilingual.currentLanguage());
  if (fromWindow) return mapToSupportedLanguage(fromWindow);
  return "en";
}

export async function resolveWidgetLocale(lang: WidgetLangCode): Promise<string> {
  const locale = await readString(() => i18n.getLocale());
  if (locale) return locale;
  if (lang === "zh") return "zh-CN";
  if (lang === "pt") return "pt-BR";
  return lang;
}

export function t(
  lang: WidgetLangCode,
  key: WidgetMessageKey,
  vars?: Record<string, string | number>,
): string {
  const template = catalogs[lang][key] ?? EN[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = vars[name];
    return value === undefined ? `{${name}}` : String(value);
  });
}

export function useResolvedWidgetLanguage(setting: WidgetLanguageSetting): WidgetLangCode {
  const [lang, setLang] = useState<WidgetLangCode>(() =>
    isWidgetLangCode(setting) ? setting : "en",
  );
  useEffect(() => {
    let cancelled = false;
    void resolveWidgetLanguage(setting).then((next) => {
      if (!cancelled) setLang(next);
    });
    return () => {
      cancelled = true;
    };
  }, [setting]);
  return lang;
}

export function useResolvedWidgetLocale(lang: WidgetLangCode): string {
  const [locale, setLocale] = useState<string>(lang);
  useEffect(() => {
    let cancelled = false;
    void resolveWidgetLocale(lang).then((next) => {
      if (!cancelled) setLocale(next);
    });
    return () => {
      cancelled = true;
    };
  }, [lang]);
  return locale;
}
